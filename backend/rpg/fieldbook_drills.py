def fieldbook_drills(question: RPGChallengeInternal, item: KnowledgeItem, language: str) -> list[RPGChallengeInternal]:
    if language not in {"zh", "en"} or item.exam_question or question.knowledge_id != item.knowledge_id:
        return []
    receipt = re.fullmatch(r"lantern-fieldbook-(zh|en)\.txt\s*/\s*(?:第\s*(\d+)\s*行|line\s+(\d+))", item.source_ref, re.I)
    if not receipt or not item.evidence:
        return []
    row = int(receipt[2] or receipt[3]) - 1
    if not 0 <= row < len(LESSONS):
        return []
    names, tasks = LESSONS[row]
    edition = receipt[1].lower()
    line = unicodedata.normalize("NFKC", item.evidence).strip()
    digest = sha256(line.encode("utf8")).hexdigest()[:12]
    if item.term.casefold() != names[int(edition == "en")].casefold() or digest != _LINES[edition][row]:
        return []
    lang = int(language == "en")
    cards = []
    for index, task in enumerate(tasks):
        choices = [x if isinstance(x, str) else x[lang] for x in task.choices]
        cards.append(drill_card(question, f"fieldbook-{row+1}-{index+1}", task.prompt[lang], choices,
                                task.hint[lang], task.reasoning[lang]))
    return cards
